import type { ReactElement, ReactNode } from "react";
import { describe, expect, it, vi } from "vitest";
import { build_user_dto } from "../support/factories";

vi.mock("next/navigation", () => ({ redirect: vi.fn() }));
vi.mock("next/font/google", () => ({
  Geist: () => ({ variable: "font-geist-sans" }),
  Geist_Mono: () => ({ variable: "font-geist-mono" }),
}));
vi.mock("@/lib/auth/session", () => ({ get_session: vi.fn() }));
vi.mock("@/services/auth_service", () => ({ find_user: vi.fn() }));

import { redirect } from "next/navigation";
import AppLayout from "@/app/(app)/layout";
import CatalogPage, { metadata as catalog_metadata } from "@/app/(app)/catalog/page";
import DashboardPage, { metadata as dashboard_metadata } from "@/app/(app)/dashboard/page";
import PortfolioDetailPage from "@/app/(app)/portfolios/[id]/page";
import PortfolioTransactionsPage from "@/app/(app)/portfolios/[id]/transactions/page";
import PortfoliosPage from "@/app/(app)/portfolios/page";
import ProfilePage from "@/app/(app)/profile/page";
import SimulatorPage from "@/app/(app)/simulator/page";
import ForgotPasswordPage from "@/app/(auth)/forgot_password/page";
import ResetPasswordPage from "@/app/(auth)/reset_password/page";
import SignInPage from "@/app/(auth)/sign_in/page";
import SignUpPage from "@/app/(auth)/sign_up/page";
