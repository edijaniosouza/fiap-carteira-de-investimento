type Element = ReactElement<Record<string, unknown>>;

// Next.js page props are generated by `next typegen`; tests build them by hand.
function page_props(params: Record<string, string> = {}, search_params: Record<string, string | string[]> = {}) {
  return { params: Promise.resolve(params), searchParams: Promise.resolve(search_params) } as never;
}

async function catalog_filters(search_params: Record<string, string | string[]>) {
  const element = (await CatalogPage(page_props({}, search_params))) as Element;
  expect(element.type).toBe(CatalogContainer);
  return element.props.url_filters;
}

describe("app pages", () => {
  it("HomePage redirects to the dashboard", () => {
    HomePage();
    expect(redirect).toHaveBeenCalledWith("/dashboard");
  });

  it("AppLayout wraps pages in the app shell", () => {
    const element = AppLayout({ children: "conteúdo" }) as Element;
    expect(element.type).toBe(AppShellContainer);
    expect(element.props.children).toBe("conteúdo");
  });

  it.each([
    [DashboardPage, DashboardContainer],
    [PortfoliosPage, PortfolioListContainer],
    [ProfilePage, ProfileContainer],
    [SimulatorPage, SimulatorContainer],
    [ForgotPasswordPage, ForgotPasswordContainer],
    [SignUpPage, SignUpContainer],
  ] as const)("%o renders its container", (Page, Container) => {
    expect((Page as () => Element)().type).toBe(Container);
  });

  it("exports page titles", () => {
    expect(dashboard_metadata.title).toBe("Dashboard");
    expect(catalog_metadata.title).toBe("Catálogo");
    expect(root_metadata.title).toEqual({ default: "Minha Carteira", template: "%s · Minha Carteira" });
  });

  it("portfolio pages pass the id param", async () => {
    const detail = (await PortfolioDetailPage(page_props({ id: "p1" }))) as Element;
    expect(detail.type).toBe(PortfolioDetailContainer);
    expect(detail.props.portfolio_id).toBe("p1");

    const transactions = (await PortfolioTransactionsPage(page_props({ id: "p1" }))) as Element;
    expect(transactions.type).toBe(TransactionListContainer);
    expect(transactions.props.portfolio_id).toBe("p1");
  });

  it("SignInPage forwards the next path only when it is a string", async () => {
    const with_next = (await SignInPage(page_props({}, { next: "/catalog" }))) as Element;
    expect(with_next.type).toBe(SignInContainer);
    expect(with_next.props.next_path).toBe("/catalog");

    const with_array = (await SignInPage(page_props({}, { next: ["/a", "/b"] }))) as Element;
    expect(with_array.props.next_path).toBeNull();
  });

  it("ResetPasswordPage forwards the token only when it is a string", async () => {
    const with_token = (await ResetPasswordPage(page_props({}, { token: "abc" }))) as Element;
    expect(with_token.type).toBe(ResetPasswordContainer);
    expect(with_token.props.token).toBe("abc");

    const without_token = (await ResetPasswordPage(page_props())) as Element;
    expect(without_token.props.token).toBeNull();
  });

  describe("CatalogPage URL filters", () => {
    it("returns null without filters", async () => {
      await expect(catalog_filters({})).resolves.toBeNull();
    });

    it("reads valid filters", async () => {
      await expect(catalog_filters({ group: "FIXED_INCOME", type: "CDB", q: "110", page: "3" })).resolves.toEqual({
        group: "FIXED_INCOME",
        type: "CDB",
        q: "110",
        page: 3,
      });
    });

    it("uses the first value of repeated params and truncates long queries", async () => {
      await expect(catalog_filters({ group: ["VARIABLE_INCOME", "FIXED_INCOME"], q: "a".repeat(80) })).resolves.toEqual({
        group: "VARIABLE_INCOME",
        q: "a".repeat(50),
      });
    });

    it("ignores invalid values", async () => {
      await expect(catalog_filters({ group: "CRYPTO", type: "COIN", page: "0" })).resolves.toBeNull();
      await expect(catalog_filters({ page: "1.5" })).resolves.toBeNull();
      await expect(catalog_filters({ page: "abc" })).resolves.toBeNull();
    });
  });
});

describe("RootLayout", () => {
  async function render_layout() {
    const html = (await RootLayout({ children: "página" } as never)) as Element;
    const body = html.props.children as Element;
    const [provider] = body.props.children as Element[];
    return { html, provider };
  }

  it("hydrates the store with the signed in user", async () => {
    const user = build_user_dto();
    vi.mocked(get_session).mockResolvedValue({ user_id: "user_1", email: "maria@example.com" });
    vi.mocked(find_user).mockResolvedValue(user);

    const { html, provider } = await render_layout();

    expect(html.props.lang).toBe("pt-BR");
    expect(html.props.className).toContain("font-geist-sans font-geist-mono");
    expect(provider.type).toBe(StoreProvider);
    expect(provider.props.current_user).toEqual(user);
    expect((provider.props as { children: ReactNode }).children).toBe("página");
    expect(find_user).toHaveBeenCalledWith("user_1");
  });

  it("renders without user when there is no session", async () => {
    vi.mocked(get_session).mockResolvedValue(null);

    const { provider } = await render_layout();

    expect(provider.props.current_user).toBeNull();
    expect(find_user).not.toHaveBeenCalled();
  });
});
